from google import genai
from getpass import getpass

# Experiment 3: Iterative Prompt Refinement

api_key = getpass("Enter your Gemini API key: ")

if not api_key.strip():
    raise ValueError("API key cannot be empty.")

client = genai.Client(api_key=api_key)
MODEL = "gemini-3.1-flash-lite"

def ask_llm(prompt):
    try:
        response = client.models.generate_content(
            model=MODEL,
            contents=prompt,
            config={
                "temperature": 0.5,
                "max_output_tokens": 500
            }
        )
        return response.text or "No response generated."

    except Exception as e:
        return f"API/Network Error: {e}"


# Iteration 0: Baseline prompt
prompt0 = "Explain photosynthesis to a 10-year-old."

# Iteration 1: Add analogy and length limit
prompt1 = (
    "You are a friendly science teacher. Explain photosynthesis "
    "to a 10-year-old using a simple analogy. Use 3 short sentences "
    "and avoid technical jargon."
)

# Iteration 2: Add mnemonic and diagram description
prompt2 = (
    "You are a friendly science teacher. Explain photosynthesis "
    "to a 10-year-old in 3 short sentences using a simple analogy. "
    "Avoid technical jargon. Add a memory trick and describe "
    "a simple text-only diagram."
)

prompts = [prompt0, prompt1, prompt2]

responses = []

for i, prompt in enumerate(prompts):
    print("\n" + "=" * 50)

    if i == 0:
        print("ITERATION 0 - BASELINE")
    elif i == 1:
        print("ITERATION 1 - ANALOGY + SHORTER EXPLANATION")
    else:
        print("ITERATION 2 - MNEMONIC + DIAGRAM")

    print("=" * 50)
    print("Prompt:", prompt)

    answer = ask_llm(prompt)
    responses.append(answer)

    print("\nResponse:")
    print(answer)

    print("\nAnalysis:")
    if i == 0:
        print("Basic explanation requested; it may lack an analogy or memory aid.")
    elif i == 1:
        print("An analogy and sentence limit make the explanation simpler.")
    else:
        print("The memory trick and diagram description help recall and visualization.")


# Save all prompts and responses to a text file
with open("experiment3_results.txt", "w", encoding="utf-8") as file:
    for i, (prompt, answer) in enumerate(zip(prompts, responses)):
        file.write(f"ITERATION {i}\n")
        file.write(f"Prompt: {prompt}\n")
        file.write(f"Response:\n{answer}\n\n")

    file.write("FINAL SUMMARY\n")
    file.write("Iteration 0: Basic explanation.\n")
    file.write("Iteration 1: Improved simplicity with analogy and brevity.\n")
    file.write("Iteration 2: Added a memory trick and diagram description.\n")

print("\n" + "=" * 50)
print("FINAL SUMMARY")
print("=" * 50)
print("Iteration 0: Basic explanation.")
print("Iteration 1: Improved clarity using analogy and short sentences.")
print("Iteration 2: Added a memory trick and diagram description.")
